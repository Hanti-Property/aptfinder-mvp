-- ============================================================
-- 준공연도(built_year) 마스터 필드 추가
-- 작성일: 2026-09-13
-- 목적: 건축물대장 API가 다지번·다동 단지에서 상가동(근린생활시설) 등 비주거 준공일을
--       반환해 준공연도가 틀리는 문제 해결. 검수한 실측 준공연도를 마스터에 우선 저장.
--       (예: 오금현대 지번43 건축물대장에 1993년 준공 근린생활시설만 잡혀 1993으로 오인)
-- AGE 점수(RVI 가중치)에 직접 영향 → 정확도 중요.
-- 재실행 안전: IF NOT EXISTS.
-- ============================================================

ALTER TABLE recon_master
  ADD COLUMN IF NOT EXISTS built_year INTEGER;   -- 준공(사용승인) 연도. 검수 실측 우선.

COMMENT ON COLUMN recon_master.built_year IS '준공연도(사용승인). 건축물대장 API 오류(상가동 등) 방지용 검수 실측값. AGE 점수 산출 기준.';

-- 오금현대: 정비계획·호갱노노 확인 결과 1984년 12월 준공 (지번43 대장은 1993 상가동)
UPDATE recon_master SET built_year = 1984, updated_at = NOW()
WHERE asset_id = 'SEL-SP-OGM-001';
